r"""
generate_paper_results.py — Generate paper LaTeX tables directly from
evaluation/ JSON artifacts. Never hand-type a number into the paper.

RECTIFIED (external review item 2): a prior version of this paper had
manually-retyped result numbers that drifted out of sync with the actual
evaluation artifacts (a stale table describing a pre-fix, 726-claim
annotation round sat alongside the current, post-fix numbers, in the same
repository). This script closes that gap for every table whose numbers
come from a single JSON artifact: it reads evaluation/*/results*.json and
writes the corresponding \begin{table}...\end{table} block to
paper/generated/*.tex, which the paper then \input{}s. Regenerating the
paper's tables after any experiment re-run is exactly:

    poetry run python evaluation/annotation/score.py
    poetry run python evaluation/controlled/score_controlled.py <run_id>
    poetry run python evaluation/ablation/run_ablation.py
    poetry run python scripts/generate_paper_results.py

Prose paragraphs that interpret these numbers are still hand-written (this
script does not attempt to generate natural-language discussion) — but the
numbers therein should be copied from this script's own printed summary,
not retyped from memory, and re-checked whenever the JSON changes.

Run with: poetry run python scripts/generate_paper_results.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVAL = ROOT / "evaluation"
OUT_DIR = ROOT / "paper" / "generated"


def load(path: Path):
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def pct(x: float) -> str:
    return f"{x * 100:.1f}\\%"


def generate_reference_results_table(data: dict) -> str:
    rel = data.get("relationship_annotation", {})
    per_class = rel.get("smriti_per_class_prf1", {})
    rows = []
    for label in ["SUPPORTS", "CONTRADICTS", "REFINES", "NEUTRAL"]:
        c = per_class.get(label)
        if not c:
            continue
        rows.append(
            f"{label:<12} & {pct(c['precision'])} & {pct(c['recall'])} & "
            f"{pct(c['f1'])} & {c['support']} \\\\"
        )
    rows_str = "\n".join(rows)
    contradicts_ci = per_class.get("CONTRADICTS", {}).get("precision_95ci", {})
    contradicts_ci_clustered = per_class.get("CONTRADICTS", {}).get("precision_95ci_clustered_by_document", {})
    n_agreed = rel.get("n_agreed_excl_unsure", "?")
    kappa = rel.get("inter_pass_kappa", "?")
    ci_lower = contradicts_ci.get("ci_lower")
    ci_upper = contradicts_ci.get("ci_upper")
    ci_n = contradicts_ci.get("n_items")
    ci_str = (
        f"[{pct(ci_lower)}, {pct(ci_upper)}]" if ci_lower is not None else "[--, --]"
    )
    clustered_lower = contradicts_ci_clustered.get("ci_lower")
    clustered_upper = contradicts_ci_clustered.get("ci_upper")
    clustered_str = (
        f"[{pct(clustered_lower)}, {pct(clustered_upper)}]" if clustered_lower is not None else None
    )
    clustered_sentence = (
        f" Resampling by source document instead of by item (cluster bootstrap, "
        f"since multiple pairs anchored on the same document are not "
        f"independent) widens this slightly to {clustered_str}."
        if clustered_str else ""
    )
    return f"""% AUTO-GENERATED by scripts/generate_paper_results.py from
% evaluation/annotation/results_summary.json. Do not hand-edit.
\\begin{{table}}[t]
\\centering
\\small
\\begin{{tabular}}{{lrrrr}}
\\toprule
\\textbf{{Label}} & \\textbf{{P}} & \\textbf{{R}} & \\textbf{{F1}} & \\textbf{{N (gold)}} \\\\
\\midrule
{rows_str}
\\bottomrule
\\end{{tabular}}
\\caption{{SMRITI's per-class precision/recall/F1 against the {n_agreed}
inter-pass-agreed (excluding UNSURE) relationship labels in the fresh
SMRITI-Reference sample ($\\kappa={kappa}$ between passes). CONTRADICTS
precision's 95\\% bootstrap CI is {ci_str} ($n={ci_n}$
SMRITI-predicted-CONTRADICTS items in this sample).{clustered_sentence}}}
\\label{{tab:reference-relationships}}
\\end{{table}}
"""


def generate_controlled_results_table(data: dict) -> str:
    per_cat = data.get("per_category", {})
    order = ["direct", "negated", "numeric", "temporal", "entity", "attribute"]
    rows = []
    for cat in order:
        c = per_cat.get(cat)
        if not c:
            continue
        recall = c["retrieved"] / c["total"] if c["total"] else 0.0
        acc = c["correct"] / c["retrieved"] if c["retrieved"] else None
        acc_str = pct(acc) if acc is not None else "--"
        rows.append(f"{cat:<12} & {pct(recall)} & {acc_str} & {c['total']} \\\\")

    def agg_row(label, cats):
        total = sum(per_cat[c]["total"] for c in cats if c in per_cat)
        retrieved = sum(per_cat[c]["retrieved"] for c in cats if c in per_cat)
        correct = sum(per_cat[c]["correct"] for c in cats if c in per_cat)
        recall = retrieved / total if total else 0.0
        acc = correct / retrieved if retrieved else None
        acc_str = pct(acc) if acc is not None else "--"
        return f"\\emph{{{label}}} & {pct(recall)} & {acc_str} & {total} \\\\"

    all_contra_row = agg_row("all CONTRADICTS", order)
    supports_row = None
    neutral_row = None
    if "supports" in per_cat:
        c = per_cat["supports"]
        recall = c["retrieved"] / c["total"] if c["total"] else 0.0
        acc = c["correct"] / c["retrieved"] if c["retrieved"] else None
        supports_row = f"SUPPORTS & {pct(recall)} & {pct(acc) if acc is not None else '--'} & {c['total']} \\\\"
    if "neutral" in per_cat:
        c = per_cat["neutral"]
        recall = c["retrieved"] / c["total"] if c["total"] else 0.0
        neutral_row = f"NEUTRAL & {pct(recall)} & -- & {c['total']} \\\\"

    overall = data.get("overall", {})
    overall_recall = data.get("overall_retrieval_recall", 0.0)
    overall_acc = data.get("overall_classification_accuracy_given_retrieved", 0.0)
    r_ci = data.get("retrieval_recall_bootstrap_ci", {})
    a_ci = data.get("classification_accuracy_bootstrap_ci", {})

    rows_str = "\n".join(rows)
    return f"""% AUTO-GENERATED by scripts/generate_paper_results.py from
% evaluation/controlled/results.json. Do not hand-edit.
\\begin{{table}}[t]
\\centering
\\small
\\begin{{tabular}}{{lrrr}}
\\toprule
\\textbf{{Category}} & \\textbf{{Recall}} & \\textbf{{Acc.\\ given retrieved}} & \\textbf{{N}} \\\\
\\midrule
{rows_str}
\\midrule
{all_contra_row}
{supports_row or ""}
{neutral_row or ""}
\\midrule
\\textbf{{Overall}} & \\textbf{{{pct(overall_recall)}}} & \\textbf{{{pct(overall_acc)}}} & \\textbf{{{overall.get('total', '?')}}} \\\\
\\bottomrule
\\end{{tabular}}
\\caption{{SMRITI-Controlled-v1 results, post-fix. Retrieval recall 95\\% CI
(bootstrap, $n = {r_ci.get('n_items', '?')}$): [{pct(r_ci.get('ci_lower', 0))}, {pct(r_ci.get('ci_upper', 0))}].
Classification accuracy given retrieval, 95\\% CI ($n = {a_ci.get('n_items', '?')}$): [{pct(a_ci.get('ci_lower', 0))}, {pct(a_ci.get('ci_upper', 0))}].}}
\\label{{tab:controlled}}
\\end{{table}}
"""


def generate_hard_neutral_table(data: dict) -> str:
    per_cat = data.get("per_category", {})
    hard_cats = [
        ("neutral_hard_same_topic", "Same topic, diff.\\ proposition"),
        ("neutral_hard_lexical_collision", "Lexical collision"),
        ("neutral_hard_adjacent_non_conflicting", "Adjacent, non-conflicting"),
    ]
    rows = []
    for key, label in hard_cats:
        c = per_cat.get(key)
        if not c:
            continue
        recall = c["retrieved"] / c["total"] if c["total"] else 0.0
        false_contra = c["retrieved"] - c["correct"]
        rows.append(
            f"{label} & {c['total']} & {c['retrieved']} & {pct(recall)} & {false_contra} \\\\"
        )
    rows_str = "\n".join(rows)
    return f"""% AUTO-GENERATED by scripts/generate_paper_results.py from
% evaluation/controlled/results.json. Do not hand-edit.
\\begin{{table}}[t]
\\centering
\\small
\\begin{{tabular}}{{lrrrr}}
\\toprule
\\textbf{{Hard-neutral category}} & \\textbf{{N}} & \\textbf{{Retrieved}} & \\textbf{{Recall}} & \\textbf{{Misclassified}} \\\\
\\midrule
{rows_str}
\\bottomrule
\\end{{tabular}}
\\caption{{SMRITI-Controlled's hard-neutral extension: NEUTRAL pairs
deliberately constructed to be topically related (unlike the original
six ``easy'' NEUTRAL pairs, which share no vocabulary at all and are
never retrieved). ``Misclassified'' counts retrieved pairs the resolver
labeled anything other than NEUTRAL --- the false-CONTRADICTS/SUPPORTS/
REFINES rate on pairs the relatedness gate cannot reject by construction,
since they genuinely share topic or vocabulary.}}
\\label{{tab:hard-neutral}}
\\end{{table}}
"""


def generate_ablation_table(data: dict) -> str:
    results = data.get("results", [])
    rows = []
    for r in results:
        sign = "+" if r["mean_shift"] >= 0 else "−"
        signal_escaped = r["signal"].replace("_", r"\_")
        rows.append(
            f"\\texttt{{{signal_escaped}}} & {r['original_weight']:.2f} & "
            f"${sign}{abs(r['mean_shift']):.2f}$ & {r['pearson_r_vs_baseline']:.3f} \\\\"
        )
    rows_str = "\n".join(rows)
    n_signals = len(results)
    return f"""% AUTO-GENERATED by scripts/generate_paper_results.py from
% evaluation/ablation/results.json. Do not hand-edit.
\\begin{{table}}[t]
\\centering
\\small
\\begin{{tabular}}{{lrrr}}
\\toprule
\\textbf{{Signal}} & \\textbf{{Weight}} & \\textbf{{Mean shift}} & $r$ \\\\
\\midrule
{rows_str}
\\bottomrule
\\end{{tabular}}
\\caption{{Effect of zeroing each of the {n_signals} signals' policy weight on
the {data.get('n_claims', '?')}-claim SMRITI-Reference reliability
distribution (baseline mean $\\mathrm{{RI}}={data.get('baseline_mean_ri', '?')}$/100).
Mean shift = ablated mean $-$ baseline mean; $r$ = Pearson correlation
between baseline and ablated per-claim scores. Ranked by mean absolute
per-claim delta, most to least disruptive.}}
\\label{{tab:ablation}}
\\end{{table}}
"""


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    summary_lines = []

    ref = load(EVAL / "annotation" / "results_summary.json")
    if ref:
        (OUT_DIR / "reference_results_table.tex").write_text(
            generate_reference_results_table(ref), encoding="utf-8"
        )
        summary_lines.append("Wrote paper/generated/reference_results_table.tex")
    else:
        summary_lines.append("SKIPPED reference_results_table.tex (no results_summary.json)")

    controlled = load(EVAL / "controlled" / "results.json")
    if controlled:
        (OUT_DIR / "controlled_results_table.tex").write_text(
            generate_controlled_results_table(controlled), encoding="utf-8"
        )
        (OUT_DIR / "hard_neutral_table.tex").write_text(
            generate_hard_neutral_table(controlled), encoding="utf-8"
        )
        summary_lines.append("Wrote paper/generated/controlled_results_table.tex")
        summary_lines.append("Wrote paper/generated/hard_neutral_table.tex")
    else:
        summary_lines.append("SKIPPED controlled_results_table.tex (no controlled/results.json)")

    ablation = load(EVAL / "ablation" / "results.json")
    if ablation:
        (OUT_DIR / "ablation_table.tex").write_text(
            generate_ablation_table(ablation), encoding="utf-8"
        )
        summary_lines.append("Wrote paper/generated/ablation_table.tex")
    else:
        summary_lines.append("SKIPPED ablation_table.tex (no ablation/results.json)")

    print("\n".join(summary_lines))


if __name__ == "__main__":
    main()
